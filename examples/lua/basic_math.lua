-- Basic arithmetic operations
a = 10
b = 5

-- Addition
sum = a + b
print(sum)  -- Will print 15

-- Subtraction
diff = a - b
print(diff)  -- Will print 5

-- Multiplication
prod = a * b
print(prod)  -- Will print 50

-- Division
quot = a / b
print(quot)  -- Will print 2

-- Modulo
rem = a % b
print(rem)  -- Will print 0 